"""Free voiceover + synced captions with Piper (no ElevenLabs credits).

usage: python3 scripts/piper_ep.py script.json public/<dir>/voz.mp3 src/.../epN-voz.ts

script.json:
{
  "voice": "/home/user/piper-voices/es_ES-davefx-medium.onnx",
  "lengthScale": 0.92,          # < 1 = faster
  "pause": 0.25,                # seconds between lines
  "lines": [
    {"say": "Faltan dos días para GTA seis.", "show": "Faltan 2 días para GTA 6."},
    {"say": "Uno: ...", "scene": true},      # scene=true -> a scene starts on this line
    ...
  ]
}

Each line is synthesised separately, so scene cuts land exactly on line starts.
Word timings inside a line are spread by word length (good enough for captions).
"""
import json, os, subprocess, sys, tempfile, wave

spec_path, out_mp3, out_ts = sys.argv[1:4]
spec = json.load(open(spec_path))
voice = spec["voice"]
ls = str(spec.get("lengthScale", 0.92))
pause = float(spec.get("pause", 0.25))

tmp = tempfile.mkdtemp()
wavs, caps, starts = [], [], []
t = 0.0
rate = None
for i, line in enumerate(spec["lines"]):
    wav = os.path.join(tmp, f"l{i}.wav")
    subprocess.run(["python3", "-m", "piper", "-m", voice, "--length-scale", ls, "-f", wav],
                   input=line["say"].encode(), check=True, capture_output=True)
    with wave.open(wav) as w:
        rate = w.getframerate()
        dur = w.getnframes() / rate
    wavs.append(wav)
    if line.get("scene"):
        starts.append(round(t * 1000))
    words = (line.get("show") or line["say"]).split()
    # Trim ~8% lead/tail silence Piper adds around speech.
    s0, s1 = t + dur * 0.04, t + dur * 0.96
    total = sum(len(w) + 2 for w in words)
    cur = s0
    for w in words:
        d = (s1 - s0) * (len(w) + 2) / total
        a, b = round(cur * 1000), round((cur + d) * 1000)
        caps.append({"text": (" " if caps else "") + w, "startMs": a, "endMs": b, "timestampMs": (a + b) // 2, "confidence": None})
        cur += d
    t += dur + pause

# Concatenate with silences.
listing = os.path.join(tmp, "list.txt")
sil = os.path.join(tmp, "sil.wav")
subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-f", "lavfi", "-i", f"anullsrc=r={rate}:cl=mono", "-t", str(pause), sil], check=True)
with open(listing, "w") as f:
    for wv in wavs:
        f.write(f"file '{wv}'\nfile '{sil}'\n")
os.makedirs(os.path.dirname(out_mp3), exist_ok=True)
subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-f", "concat", "-safe", "0", "-i", listing,
                "-af", "loudnorm=I=-14:TP=-1.5", "-ar", "44100", "-b:a", "192k", out_mp3], check=True)

with open(out_ts, "w") as f:
    f.write("// Generated by scripts/piper_ep.py (Piper TTS).\nimport type { Caption } from \"@remotion/captions\";\n\n")
    f.write(f"export const SCENE_STARTS_MS = {json.dumps(starts)};\nexport const VOICE_END_MS = {caps[-1]['endMs']};\n\n")
    f.write("export const CAPTIONS: Caption[] = " + json.dumps(caps, ensure_ascii=False, indent=1) + ";\n")
print("duration", round(t - pause, 2), "s · scenes", starts, "· words", len(caps))
